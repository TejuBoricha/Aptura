/** Short git hash of HEAD, or "unknown" when git (or a repository) is not available, e.g. building from a source archive. */
fun gitRevision(): String = try {
    providers.exec {
        commandLine("git", "rev-parse", "--short=8", "HEAD")
        isIgnoreExitValue = true
    }.standardOutput.asText.get().trim().ifBlank { "unknown" }
} catch (_: Throwable) {
    "unknown"
}

/**
 * Writes the release runtime dependency graph as `group:name:version <- requiredBy, requiredBy`, one line per library.
 * The unit tests read it (see DependencyInvariantsTest): the old check grepped this build file for words, which could
 * not see transitive libraries at all.
 */
abstract class WriteDependencyReport : DefaultTask() {
    // The resolved graph cannot be fingerprinted as an input, so the task always runs; it is cheap.
    @get:Internal
    abstract val rootComponent: Property<ResolvedComponentResult>

    @get:OutputFile
    abstract val report: RegularFileProperty

    init {
        outputs.upToDateWhen { false }
    }

    @TaskAction
    fun write() {
        fun label(component: ResolvedComponentResult): String {
            val id = component.id
            if (id is ProjectComponentIdentifier) return "project ${id.projectPath}"
            val module = component.moduleVersion
            return if (module == null) id.displayName else "${module.group}:${module.name}:${module.version}"
        }

        val requiredBy = sortedMapOf<String, MutableSet<String>>()
        val seen = mutableSetOf<ResolvedComponentResult>()
        val queue = ArrayDeque<ResolvedComponentResult>()
        val root = rootComponent.get()
        queue.add(root)
        seen.add(root)
        while (queue.isNotEmpty()) {
            val from = queue.removeFirst()
            for (dependency in from.dependencies) {
                // Constraints only restrict versions of libraries something else already pulled in.
                if (dependency !is ResolvedDependencyResult || dependency.isConstraint) continue
                val to = dependency.selected
                requiredBy.getOrPut(label(to)) { sortedSetOf() }.add(label(from))
                if (seen.add(to)) queue.add(to)
            }
        }
        report.get().asFile.apply {
            parentFile.mkdirs()
            writeText(
                "# Aptura release runtime dependencies (generated by writeReleaseRuntimeDependencies)\n" +
                    requiredBy.entries.joinToString("") { (library, parents) -> "$library <- ${parents.joinToString(", ")}\n" }
            )
        }
    }
}

/**
 * Fails the build when the release APK still contains a network stack or a telemetry SDK. Dependency graphs say what is
 * *on the classpath*; R8 decides what is *shipped*, so the shipped code is checked as well.
 *
 * R8 renames classes (`okhttp3.internal.http.HttpHeaders` becomes `xb.e`), so searching the dex for library names finds
 * almost nothing. The primary check therefore reads R8's mapping file, which lists every class that survived under its
 * original name; the dex text search is kept as a second net for names R8 left in place.
 */
abstract class VerifyApkContents : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val apkDirectory: DirectoryProperty

    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val mappingFile: RegularFileProperty

    @get:Input
    abstract val forbiddenPackages: ListProperty<String>

    @get:OutputFile
    abstract val report: RegularFileProperty

    @TaskAction
    fun verify() {
        val forbidden = forbiddenPackages.get()
        val findings = mutableListOf<String>()

        // Classes R8 kept, by original name. Removed classes are mapped to "R8$$REMOVED$$CLASS$$n" and do not count.
        val classLine = Regex("^([A-Za-z0-9_.$]+) -> ([A-Za-z0-9_.$]+):$")
        val keptByPackage = sortedMapOf<String, Int>()
        var keptClasses = 0
        mappingFile.get().asFile.useLines { lines ->
            for (line in lines) {
                val match = classLine.find(line) ?: continue
                if (match.groupValues[2].contains("REMOVED")) continue
                keptClasses++
                val original = match.groupValues[1]
                forbidden.map { it.replace('/', '.') }.firstOrNull { original.startsWith(it) }?.let { keptByPackage.merge(it, 1, Int::plus) }
            }
        }
        check(keptClasses > 1000) { "The R8 mapping lists only $keptClasses classes; refusing to report a pass" }
        keptByPackage.forEach { (pkg, count) -> findings += "R8 kept $count class(es) from $pkg" }

        val apks = apkDirectory.get().asFile.walkTopDown().filter { it.isFile && it.extension == "apk" }.toList()
        check(apks.isNotEmpty()) { "No release APK found in ${apkDirectory.get().asFile} to verify" }
        var dexFiles = 0
        for (apk in apks) {
            ZipFile(apk).use { zip ->
                for (entry in zip.entries()) {
                    if (!entry.name.endsWith(".dex")) continue
                    dexFiles++
                    // ISO-8859-1 maps bytes 1:1, so class descriptors in the dex string table are searchable as text.
                    val text = String(zip.getInputStream(entry).use { it.readBytes() }, Charsets.ISO_8859_1)
                    forbidden.filter { text.contains(it) }.forEach { findings += "${apk.name}!${entry.name} still names $it" }
                }
            }
        }
        check(dexFiles > 0) { "The release APKs contain no dex files; refusing to report a pass" }
        report.get().asFile.apply {
            parentFile.mkdirs()
            writeText(
                "Checked $keptClasses kept classes and $dexFiles dex file(s) in ${apks.size} APK(s) against ${forbidden.size} forbidden packages.\n" +
                    findings.joinToString("\n")
            )
        }
        if (findings.isNotEmpty()) {
            throw GradleException("The release APK contains forbidden code (zero-network / zero-telemetry invariants):\n" + findings.joinToString("\n"))
        }
    }
}

/** Hands the unit tests the files they verify, as system properties; the files are declared inputs of the test task. */
class InvariantInputs(
    @get:InputFile @get:PathSensitive(PathSensitivity.NONE) val releaseManifest: Provider<RegularFile>,
    @get:InputFile @get:PathSensitive(PathSensitivity.NONE) val releaseDependencies: Provider<RegularFile>
) : CommandLineArgumentProvider {
    override fun asArguments(): Iterable<String> = listOf(
        "-Daptura.invariants.releaseManifest=${releaseManifest.get().asFile.absolutePath}",
        "-Daptura.invariants.releaseDependencies=${releaseDependencies.get().asFile.absolutePath}"
    )
}

val releaseMergedManifest: RegularFileProperty = objects.fileProperty()
val releaseApkDirectory: DirectoryProperty = objects.directoryProperty()
val releaseMappingFile: RegularFileProperty = objects.fileProperty()

val writeReleaseDependencies = tasks.register<WriteDependencyReport>("writeReleaseRuntimeDependencies") {
    group = "verification"
    description = "Writes the release runtime dependency graph for the invariant tests."
    rootComponent.set(configurations.named("releaseRuntimeClasspath").flatMap { it.incoming.resolutionResult.rootComponent })
    report.set(layout.buildDirectory.file("invariants/release-runtime-dependencies.txt"))
}

