#!/usr/bin/env python3
"""
tools/corpus/generate_adversarial_media.py
Generates adversarial media corpus per spec/12A_B0_INSTRUMENTATION.md §2.5.
All files exist to test error taxonomy (FR-PLAY-004) and safe teardown without crash.
"""

import os
import subprocess
from pathlib import Path

OUT_DIR = Path("fixtures/adv_media")

def ensure_dir(path: Path):
    path.mkdir(parents=True, exist_ok=True)

def generate_adversarial_files():
    ensure_dir(OUT_DIR)

    # Base valid video to derive truncated/corrupt versions from
    base_mp4 = OUT_DIR / "_base_valid.mp4"
    cmd_base = [
        "ffmpeg", "-y",
        "-f", "lavfi", "-i", "testsrc=duration=3:size=320x240:rate=24",
        "-f", "lavfi", "-i", "sine=duration=3",
        "-c:v", "libx264", "-c:a", "aac",
        str(base_mp4)
    ]
    subprocess.run(cmd_base, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

    with open(base_mp4, "rb") as f:
        valid_bytes = f.read()

    # 1. Zero-byte file
    with open(OUT_DIR / "adv_media_01_zero_byte.mp4", "wb") as f:
        pass

    # 2. 1-byte file
    with open(OUT_DIR / "adv_media_02_one_byte.mp4", "wb") as f:
        f.write(b"\x00")

    # 3. Truncated header (first 32 bytes zeroed out)
    with open(OUT_DIR / "adv_media_03_corrupt_header.mp4", "wb") as f:
        f.write(b"\x00" * 32 + valid_bytes[32:])

    # 4. Truncated mid-packet (cut in half)
    half_len = len(valid_bytes) // 2
    with open(OUT_DIR / "adv_media_04_truncated_mid.mp4", "wb") as f:
        f.write(valid_bytes[:half_len])

    # 5. Garbage bytes with valid .mp4 extension
    with open(OUT_DIR / "adv_media_05_random_garbage.mp4", "wb") as f:
        f.write(os.urandom(4096))

    # 6. Absurd declared duration in MKV / MP4 (via ffmetadata declared duration or corrupted box)
    cmd_duration = [
        "ffmpeg", "-y",
        "-f", "lavfi", "-i", "testsrc=duration=1:size=320x240:rate=24",
        "-c:v", "libx264",
        "-metadata", "duration=999999:59:59",
        str(OUT_DIR / "adv_media_06_absurd_duration.mkv")
    ]
    subprocess.run(cmd_duration, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

    # 7. Declared-duration / file-length mismatch (header says 60s, stream cut at 2s)
    # Generated by truncating after moov box
    with open(OUT_DIR / "adv_media_07_duration_length_mismatch.mp4", "wb") as f:
        f.write(valid_bytes[:min(len(valid_bytes), 12000)])

    # 8. Corrupt CRC / Bit-flipped payload
    flipped_bytes = bytearray(valid_bytes)
    # Flip bits across multiple packets
    for i in range(1000, min(5000, len(flipped_bytes)), 100):
        flipped_bytes[i] ^= 0xFF
    with open(OUT_DIR / "adv_media_08_corrupt_crc_bitflip.mp4", "wb") as f:
        f.write(flipped_bytes)

    # 9. Multi-track overload (8 audio tracks, 8 subtitle tracks in MKV)
    multi_track_cmd = [
        "ffmpeg", "-y",
        "-f", "lavfi", "-i", "testsrc=duration=2:size=320x240:rate=24",
    ]
    for _ in range(8):
        multi_track_cmd.extend(["-f", "lavfi", "-i", "sine=duration=2:frequency=440"])
    
    multi_track_cmd.extend(["-map", "0:v"])
    for i in range(1, 9):
        multi_track_cmd.extend(["-map", f"{i}:a"])
    
    multi_track_cmd.extend([
        "-c:v", "libx264",
        "-c:a", "aac",
        str(OUT_DIR / "adv_media_09_multi_track_overload.mkv")
    ])
    subprocess.run(multi_track_cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

    # 10. Fragmented MP4 with missing initialization / missing sidx/moof
    cmd_fmp4 = [
        "ffmpeg", "-y",
        "-f", "lavfi", "-i", "testsrc=duration=2:size=320x240:rate=24",
        "-c:v", "libx264",
        "-movflags", "frag_keyframe+empty_moov+default_base_moof",
        str(OUT_DIR / "adv_media_10_fmp4_base.mp4")
    ]
    subprocess.run(cmd_fmp4, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    if (OUT_DIR / "adv_media_10_fmp4_base.mp4").exists():
        with open(OUT_DIR / "adv_media_10_fmp4_base.mp4", "rb") as f:
            fmp4_bytes = f.read()
        # Drop the first 500 bytes (stripping the ftyp and moov atom)
        with open(OUT_DIR / "adv_media_10_fmp4_missing_moov.mp4", "wb") as f:
            f.write(fmp4_bytes[1024:])

    # Clean up base temporary file
    if base_mp4.exists():
        base_mp4.unlink()

def main():
    print("Generating adversarial media corpus...")
    generate_adversarial_files()
    print("Adversarial media corpus generated successfully.")

if __name__ == "__main__":
    main()
